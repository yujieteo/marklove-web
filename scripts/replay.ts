import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";
import type { Wire } from "./replay-codec.ts";

const root = resolve(import.meta.dir, "..");
const EARLY_STOP_SHARE = 0.2;
const MAX_SHOWN = 20;
const LINE_NUMBER = /(gs_file[0-9]+, )[0-9]+/g;
const SOURCE_PATH = /(gs_file[0-9]+\[\] = ")[^"]*\/(core\/[^"\/]+")/g;
const GENERATED_FROM = /^(\/\* Generated by the Goose compiler from ).*?( Do not edit\.)/m;

function sh(cmd: string[], cwd: string, env: Record<string, string> = {}): { code: number; out: string } {
    const r = Bun.spawnSync(cmd, { cwd, env: { ...process.env, ...env }, stdout: "pipe", stderr: "pipe" });
    return { code: r.exitCode, out: r.stdout.toString() + r.stderr.toString() };
}

function parseArgs(argv: string[]): { base: string | null; accept: boolean } {
    let base: string | null = null;
    let accept = false;
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === "--accept") accept = true;
        else if (a === "--base") base = argv[++i] ?? null;
        else throw new Error("Unknown argument " + String(a));
    }
    return { base, accept };
}

function defaultBase(): string {
    const mergeBase = sh(["git", "merge-base", "HEAD", "origin/main"], root);
    const head = sh(["git", "rev-parse", "HEAD"], root).out.trim();
    const candidate = mergeBase.code === 0 ? mergeBase.out.trim() : "";
    return candidate !== "" && candidate !== head ? candidate : "HEAD~1";
}

function isWireList(v: unknown): v is Wire[] {
    return Array.isArray(v);
}

function readWires(file: string): Wire[] {
    const v: unknown = JSON.parse(readFileSync(file, "utf8"));
    if (!isWireList(v)) throw new Error("Bad result file " + file);
    return v;
}

interface Named {
    fn: string;
}

function isNamed(v: unknown): v is Named[] {
    return Array.isArray(v) && v.every((r) => typeof r === "object" && r !== null && "fn" in r && typeof r.fn === "string");
}

interface Diff {
    where: string;
    base: string;
    branch: string;
}

function normalizeC(text: string): string {
    return text.replace(LINE_NUMBER, "$1N").replace(SOURCE_PATH, "$1$2").replace(GENERATED_FROM, "$1<source>$2");
}

function gooseOutputs(dir: string, tag: string, work: string): { c: string; h: string } | null {
    const c = join(work, tag + ".c");
    const h = join(work, tag + ".h");
    const r = sh(["goose", "-q", "-o", c, join(dir, "core/marklove.goose"), "--standalone", "--include", "io.h", "--header", h], dir);
    if (r.code !== 0) return null;
    return { c: normalizeC(readFileSync(c, "utf8")), h: readFileSync(h, "utf8") };
}

function firstDifference(a: string, b: string): string {
    const x = a.split("\n");
    const y = b.split("\n");
    for (let i = 0; i < Math.max(x.length, y.length); i++) {
        if (x[i] !== y[i]) return "line " + String(i + 1) + "\n  base:   " + (x[i] ?? "<end>").slice(0, 200) + "\n  branch: " + (y[i] ?? "<end>").slice(0, 200);
    }
    return "";
}

const { base: baseArg, accept } = parseArgs(process.argv.slice(2));
const base = baseArg ?? defaultBase();
const cache = join(process.env["XDG_CACHE_HOME"] ?? join(homedir(), ".cache"), "marklove-web", "replay");
rmSync(cache, { recursive: true, force: true });
mkdirSync(cache, { recursive: true });
const work = mkdtempSync(join(tmpdir(), "marklove-replay-"));
const baseDir = join(work, "base");
mkdirSync(baseDir);

const archive = Bun.spawnSync(["sh", "-c", `git archive ${JSON.stringify(base)} | tar -x -C ${JSON.stringify(baseDir)}`], { cwd: root });
if (archive.exitCode !== 0) throw new Error("Cannot read base commit " + base + ": " + archive.stderr.toString());

const diffs: Diff[] = [];
let total = 0;

const tests = readdirSync(join(root, "tests")).filter((f) => f.endsWith(".test.ts")).sort();
for (const t of tests) {
    const log = join(cache, t + ".log.json");
    writeFileSync(log, "[]");
    const cap = Bun.spawnSync(["bun", "test", "--preload", join(root, "scripts/replay-capture.ts"), join("tests", t)], {
        cwd: root,
        env: { ...process.env, MARKLOVE_CAPTURE_FILE: join(cache, t + ".jsonl") },
        stdout: "pipe",
        stderr: "pipe",
    });
    if (cap.exitCode !== 0) throw new Error("Capture run failed for " + t + "\n" + cap.stdout.toString() + cap.stderr.toString());
    const lines = readFileSync(join(cache, t + ".jsonl"), "utf8").split("\n").filter(Boolean);
    const merged: unknown[] = lines.flatMap((l): unknown[] => {
        const v: unknown = JSON.parse(l);
        return Array.isArray(v) ? v : [];
    });
    writeFileSync(log, JSON.stringify(merged));
    if (!isNamed(merged)) throw new Error("Bad capture for " + t);

    const outBase = join(cache, t + ".base.json");
    const outBranch = join(cache, t + ".branch.json");
    const driver = join(root, "scripts/replay-run.ts");
    const a = sh(["bun", driver, baseDir, log, outBase], root);
    const b = sh(["bun", driver, root, log, outBranch], root);
    if (a.code !== 0) throw new Error("Base replay failed for " + t + "\n" + a.out);
    if (b.code !== 0) throw new Error("Branch replay failed for " + t + "\n" + b.out);
    const ra = readWires(outBase);
    const rb = readWires(outBranch);
    total += merged.length;
    merged.forEach((rec, i) => {
        const x = JSON.stringify(ra[i]);
        const y = JSON.stringify(rb[i]);
        if (x !== y) diffs.push({ where: t + " call " + String(i) + " " + rec.fn, base: x.slice(0, 300), branch: y.slice(0, 300) });
    });
}

const baseC = gooseOutputs(baseDir, "base", work);
const branchC = gooseOutputs(root, "branch", work);
if (baseC === null || branchC === null) throw new Error("goose failed to compile core/marklove.goose");
total += 2;
if (baseC.c !== branchC.c) diffs.push({ where: "goose C output", base: "", branch: firstDifference(baseC.c, branchC.c) });
if (baseC.h !== branchC.h) diffs.push({ where: "goose C header", base: "", branch: firstDifference(baseC.h, branchC.h) });

rmSync(work, { recursive: true, force: true });

console.log("replay: base " + base + ", " + String(total) + " outputs compared, " + String(diffs.length) + " differ");
if (diffs.length === 0) process.exit(0);
const share = diffs.length / Math.max(total, 1);
if (share > EARLY_STOP_SHARE) console.log("Large change: " + String(Math.round(share * 100)) + "% of the outputs differ.");
for (const d of diffs.slice(0, MAX_SHOWN)) console.log("\n" + d.where + "\n  base:   " + d.base + "\n  branch: " + d.branch);
if (diffs.length > MAX_SHOWN) console.log("\n... " + String(diffs.length - MAX_SHOWN) + " more");
if (accept) {
    console.log("\nAccepted on this run (--accept).");
    process.exit(0);
}
process.exit(1);
